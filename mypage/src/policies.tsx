import { Link } from '@tanstack/react-router'
import type { ReactNode } from 'react'
import { ExternalLink } from './features/mypage/view'
import {
	type PublicPolicyConfig,
	readPublicPolicyConfig,
	validatePublicPolicyConfig,
} from './public-policy-config'

type PublicPolicyProps = { publicPolicyInputs?: unknown }

function policyConfig(inputs: unknown): PublicPolicyConfig {
	return (
		inputs === undefined
			? readPublicPolicyConfig()
			: validatePublicPolicyConfig(inputs)
	).config
}

export function ContactLink({
	href,
	children,
	primary = false,
}: {
	href: string
	children: ReactNode
	primary?: boolean
}) {
	return href.startsWith('mailto:') ? (
		<a
			className={primary ? 'button primary' : 'external-link'}
			href={href}
			rel="noreferrer"
		>
			{children}
		</a>
	) : (
		<ExternalLink href={href} primary={primary}>
			{children}
		</ExternalLink>
	)
}

export function PublicPolicyContact({
	publicPolicyInputs,
}: PublicPolicyProps = {}) {
	const config = policyConfig(publicPolicyInputs)
	const privacyURL = config.privacyContactURL
	return (
		<>
			{config.operatorName && <p>運営者の公開表記：{config.operatorName}</p>}
			<p>
				使い方のご質問や不具合の報告は
				<Link to="/contact">一般のお問い合わせ</Link>
				へ、個人情報の開示・削除などのご請求はプライバシーの専用窓口へお寄せください。
			</p>
			{privacyURL ? (
				<p>
					<ContactLink href={privacyURL}>
						{privacyURL.startsWith('https://docs.google.com/forms/')
							? '個人情報の開示・削除などの専用フォーム'
							: '個人情報の開示・削除などの専用窓口'}
					</ContactLink>
				</p>
			) : (
				<p>個人情報・プライバシーの専用窓口は準備中です。</p>
			)}
		</>
	)
}

function EffectiveDate({ value }: { value?: string }) {
	if (!value) return null
	return (
		<p>
			施行日：
			<time dateTime={value}>{value}</time>
		</p>
	)
}

